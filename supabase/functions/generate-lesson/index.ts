import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are EduPlan AI, an expert teaching assistant for K-12 educators. You generate clear, engaging, classroom-ready content.

When asked to create lesson materials, ALWAYS respond in well-structured Markdown with these sections (use level-2 headings ##):
## 📋 Lesson Plan
- Learning Objectives (bulleted)
- Materials Needed
- Lesson Flow (with time estimates per stage: Warm-up, Direct Instruction, Guided Practice, Independent Practice, Closure)

## 📝 Worksheet
- Printable-style questions (mix of multiple choice, short answer, and one challenge problem). Include an Answer Key at the end.

## 🎮 Activities & Games
- 2–3 engaging classroom activities or games tied directly to the topic. Include instructions and group sizes.

## 🌈 Differentiation
- Support for struggling learners
- Extension for advanced learners
- Tips for ELL / accessibility

## ✅ Assessment Suggestions
- Formative and summative ideas with quick rubrics.

Use friendly, professional, encouraging language. Use emojis sparingly to add warmth. Keep formatting clean for printing.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [{ role: "system", content: systemPrompt }, ...messages],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please add credits in workspace settings." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("generate-lesson error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});